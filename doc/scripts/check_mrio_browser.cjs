// Run against a built preview with Playwright and the Chrome channel installed.
const {chromium}=require('playwright');
const fs=require('fs'),assert=require('assert/strict');
const path=require('path'),os=require('os');
const base=process.env.MARIO_DOCS_PREVIEW_URL||'http://127.0.0.1:8765/';
const out=process.env.MARIO_DOCS_QA_DIR||path.join(os.tmpdir(),'mario-mrio-browser-qa');fs.mkdirSync(out,{recursive:true});
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1050}}),errors=[];
 const assets=process.env.MARIO_DOCS_QA_ASSETS;
 if(assets)await page.route('**/_static/**',async route=>{
  const suffix=new URL(route.request().url()).pathname.split('/_static/')[1],file=path.resolve(assets,suffix||'');
  if(file.startsWith(path.resolve(assets)+path.sep)&&fs.existsSync(file))await route.fulfill({path:file});else await route.continue();
 });
 page.setDefaultTimeout(20000);page.on('pageerror',e=>errors.push(e.message));
 await page.goto(new URL('resources/data-explorer/browsers.html',base).href,{waitUntil:'networkidle',timeout:60000});
 const root=page.locator('[data-economy-browser]');
 const ready=()=>page.waitForFunction(()=>document.querySelector('[data-economy-browser]')?.getAttribute('aria-busy')==='false',{},{timeout:60000});
 await ready();
 assert.match(await page.locator('body').innerText(),/multi-regional input/);
 assert.deepEqual(await root.locator('[data-compare-family]').evaluateAll(ns=>ns.map(n=>n.value).sort()),['ADB','EMERGING','EXIOBASE','FIGARO','GLORIA','OECD','WIOD']);
 const env=root.locator('[data-bulk-action="env-extended"]');
 await env.click();await ready();
 assert.equal(await env.getAttribute('aria-pressed'),'true');
 assert.equal(await root.locator('[data-metric] option[value="ghg"]').evaluate(n=>n.disabled),false);
 for(const family of ['OECD','FIGARO','WIOD'])assert.equal(await root.locator(`[data-compare-family][value="${family}"]`).evaluate(n=>n.disabled),true);
 await root.locator('[data-metric]').selectOption('ghg');await ready();
 assert.match(await root.locator('[data-heading]').innerText(),/GHG emissions/);
 await root.locator('[data-expand-family="ADB"]').click();await ready();
 assert.ok(await root.locator('[data-compare-facet="ADB"][data-facet-key="version"]').evaluateAll(ns=>ns.every(n=>n.checked)));
 const adbOptions=await root.locator('[data-compare-facet="ADB"]').allTextContents();
 assert.ok(adbOptions.length>0);
 assert.deepEqual(await root.locator('[data-compare-facet="ADB"][data-facet-key="version"]').evaluateAll(ns=>ns.map(n=>n.value).sort()),['62 economies','72 economies']);
 await root.locator('[data-expand-family="EMERGING"]').click();await ready();
 assert.ok(await root.locator('[data-compare-facet="EMERGING"][data-facet-key="version"]').evaluateAll(ns=>ns.every(n=>n.checked)));
 assert.ok((await root.locator('[data-compare-facet="EMERGING"]').evaluateAll(ns=>ns.map(n=>n.value))).includes('E'));
 const downloadPromise=page.waitForEvent('download');await root.locator('[data-export]').click();
 const csv=await fs.promises.readFile(await (await downloadPromise).path(),'utf8');fs.writeFileSync(out+'/environmental.csv',csv);
 assert.ok(!/BEA|USEEIO|71 economies|74 economies/.test(csv));
 assert.match(csv,/EMERGING-E/);assert.match(csv,/projected onto the 146 EMERGING-E sectors/);assert.match(csv,/ADB/);assert.match(csv,/EMERGING/);assert.match(csv,/EXIOBASE/);assert.match(csv,/GLORIA/);assert.match(csv,/CC BY-NC 3.0/);assert.match(csv,/creativecommons.org\/licenses\/by-nc\/3.0\/au\//);
 await root.locator('[data-expand-family="EMERGING"]').click();await ready();
 await root.screenshot({path:out+'/environmental-light.png'});
 await page.evaluate(()=>document.documentElement.setAttribute('data-theme','dark'));await ready();
 await root.screenshot({path:out+'/environmental-dark.png'});
 // Restrict the preset to ADB: unsupported years must disappear from choices.
 for(const f of ['EXIOBASE','EMERGING','GLORIA'])await root.locator(`[data-compare-family][value="${f}"]`).uncheck();await ready();
 await root.locator('[data-picker="year"] > summary').click();
 assert.deepEqual(await root.locator('[data-options="year"] input[data-subset="year"]').evaluateAll(ns=>ns.map(n=>Number(n.value)).filter(Number.isFinite).sort((a,b)=>a-b)),[2017,2018,2019,2020,2021,2022,2023]);
 await root.locator('[data-picker="year"] > summary').click();
 await env.click();await ready();assert.equal(await env.getAttribute('aria-pressed'),'false');
 assert.equal(await root.locator('[data-metric] option[value="ghg"]').evaluate(n=>n.disabled),true);
 await env.click();await ready();
 await root.locator('[data-bulk-filter="databases"][data-bulk-action="select"]').click();await ready();
 assert.equal(await env.getAttribute('aria-pressed'),'false');
 assert.equal(await root.locator('[data-metric] option[value="ghg"]').evaluate(n=>n.disabled),true);
 await root.locator('[data-mode="focus"]').click();await ready();
 assert.deepEqual(await root.locator('[data-family] option').evaluateAll(ns=>ns.map(n=>n.value).sort()),['ADB','EMERGING','EXIOBASE','FIGARO','GLORIA','OECD','WIOD']);
 await root.locator('[data-family]').selectOption('GLORIA');await ready();
 assert.equal(await root.locator('[data-metric] option[value="gdp"]').evaluate(n=>n.disabled),false);
 assert.equal(await root.locator('[data-metric] option[value="ghg"]').evaluate(n=>n.disabled),false);
 await root.locator('[data-metric]').selectOption('ghg');await ready();
 assert.ok((await root.locator('[data-source] a').evaluateAll(ns=>ns.map(n=>n.href))).includes('https://creativecommons.org/licenses/by-nc/3.0/au/'));
 assert.match(await root.locator('[data-context]').textContent(),/CC BY-NC 3.0/);
 assert.match(await root.locator('[data-indicator-note]').innerText(),/unverified/);
 await root.screenshot({path:out+'/gloria-focus-dark.png'});
 await root.locator('[data-picker="year"] > summary').click();
 await root.locator('[data-bulk-filter="year"][data-bulk-action="clear"]').click();await ready();
 await root.locator('[data-subset="year"][value="2024"]').check();await ready();
 await root.locator('[data-picker="year"] > summary').click();
 await root.locator('[data-metric]').selectOption('ghg');await ready();
 await root.locator('[data-view="map"]').click();await ready();
 assert.ok(await root.locator('path[data-iso="ITA"]').count());
 await root.locator('[data-view="auto"]').click();await ready();
 await root.locator('[data-family]').selectOption('OECD');await ready();
 assert.equal(await root.locator('[data-metric] option[value="ghg"]').evaluate(n=>n.disabled),true);
 await root.locator('[data-mode="country"]').click();
 await page.waitForFunction(()=>document.querySelector('[data-cf-country-summary]')?.textContent==='Italy');
 await root.locator('[data-cf-country-picker] > summary').click();
 await root.locator('[data-cf-country-search]').fill('USA');await root.locator('[data-cf-country="USA"]').click();
 await page.waitForFunction(()=>document.querySelector('[data-cf-country-summary]')?.textContent.includes('United States'));
 const profiles=await root.locator('[data-cf-results]').innerText();assert.ok(!/BEA|USEEIO/.test(profiles));assert.match(profiles,/CEDA/);
 assert.match(profiles,/GLORIA/);
 const scopeDownload=page.waitForEvent('download');await root.locator('[data-cf-export]').click();
 const scopeCSV=await fs.promises.readFile(await (await scopeDownload).path(),'utf8');assert.match(scopeCSV,/CC BY-NC 3.0/);
 await root.screenshot({path:out+'/country-usa-dark.png'});
 await page.setViewportSize({width:390,height:844});
 await root.locator('[data-mode="compare"]').click();await ready();await env.click();await ready();
 await root.screenshot({path:out+'/environmental-mobile.png'});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({families:7,ghg_preset:true,adb_years:7,usa_profiles_without_national:true,csv_bytes:csv.length,errors}));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
